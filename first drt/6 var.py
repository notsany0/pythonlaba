##2.Дан список натуральных чисел. Требуется сформировать из них множество. Если какое-либо число повторяется,
#то преобразовать его в строку по образцу: например, если число 4 повторяется 3 раза, то в множестве будет следующая запись:
#само число 4, строка «44» (второе повторение, т.е. число дублируется в строке), строка «444» (третье повторение,
#т.е. строка множится на 3).
a= [1,2,2,3,3,3]
s=set()
count={}
for x in a:
    count[x] = count.get(x,0)+1
    if count[x]==1:
        s.add(x)
    else:
        s.add(str(x) * count[x])
print(s)
##3. Вводится строка текста. Сформируйте строку, в которой из исходной строки удалены все фрагменты в парных круглых скобках,
# включая эти скобки
s = input()
result = ""
stack = []
for c in s:
    if c == '(':
        stack.append(len(result))
        result += c
    elif c == ')' and stack:
        start = stack.pop()
        result = result[:start]
    else:
        result += c
print(result)

